import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
const root = new URL('../', import.meta.url);
const before = readFileSync(new URL('scripts/fixtures/admin-cron-health-before-20260920.sql', root), 'utf8');
const migration = readFileSync(new URL('supabase/sql/pending/20260920_admin_cron_health_partial.sql', root), 'utf8');
const passed = [];
const check = (name, fn) => { fn(); passed.push(name); };
await db.exec(`CREATE SCHEMA auth; CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT NULL::uuid $$;
CREATE FUNCTION public.has_role(uuid,text) RETURNS boolean LANGUAGE sql AS $$ SELECT coalesce(current_setting('fixture.is_admin',true),'false')='true' $$;
CREATE TABLE cron_run_log(edge_name text,started_at timestamptz,finished_at timestamptz,status text,error_message text);
SET fixture.is_admin='true';`);
await db.exec(before);
const edge = 'evaluate-journeys';
const all = async () => (await db.query('SELECT admin_cron_health() AS result')).rows[0].result;
const health = async () => (await all()).find(r => r.edge_name === edge);
const add = async (status, minutes=1, finished=true) => db.query(`INSERT INTO cron_run_log VALUES($1,now()-($2::text||' minutes')::interval,CASE WHEN $3::boolean THEN now()-($2::text||' minutes')::interval ELSE NULL END,$4,NULL)`, [edge,minutes,finished,status]);
const clear = async () => db.exec('TRUNCATE cron_run_log');
const metadata = async () => (await db.query("SELECT proowner,proacl,prosecdef,provolatile,proconfig FROM pg_proc WHERE oid='admin_cron_health()'::regprocedure")).rows[0];
await add('partial');
check('reproduces partial shown healthy before patch', () => {});
assert.equal((await health()).state,'ok');
const initialMeta=await metadata();
const initialHistory=(await db.query('SELECT * FROM cron_run_log')).rows;
await db.exec(migration);
const finalMeta=await metadata();
check('preserves owner, grants, stable/security and search path',()=>assert.deepEqual(finalMeta,initialMeta));
const finalHistory=(await db.query('SELECT * FROM cron_run_log')).rows;
check('migration does not rewrite history',()=>assert.deepEqual(finalHistory,initialHistory));
let r=await health();
check('partial alone degrades without inflating failures',()=>assert.deepEqual([r.state,r.partial_7d,r.failed_7d,r.failed_in_last_3],['degraded',1,0,0]));
await clear(); await add('success'); r=await health();
check('success remains healthy',()=>assert.deepEqual([r.state,r.partial_7d,r.failed_7d],['ok',0,0]));
await clear(); await add('failed'); r=await health();
check('failed remains degraded with original counters',()=>assert.deepEqual([r.state,r.partial_7d,r.failed_7d,r.failed_in_last_3],['degraded',0,1,1]));
await clear(); await add('success'); await add('partial',10); await add('failed',20); r=await health();
check('recent partial and failed remain separate',()=>assert.deepEqual([r.state,r.runs_7d,r.partial_7d,r.failed_7d],['degraded',3,1,1]));
await clear(); await add('success'); await add('partial',8*1440); r=await health();
check('old partial does not degrade a current success',()=>assert.deepEqual([r.state,r.partial_7d,r.runs_7d],['ok',0,1]));
await clear(); await add('partial',121); r=await health();
check('overdue remains critical ahead of partial',()=>assert.equal(r.state,'critical'));
await clear(); r=await health();
check('missing execution remains critical',()=>assert.deepEqual([r.state,r.partial_7d,r.runs_7d],['critical',0,0]));
await add('running',1,false); r=await health();
check('fresh running does not become partial',()=>assert.deepEqual([r.state,r.partial_7d,r.failed_in_last_3],['ok',0,0]));
await clear(); await add('partial',10); await add('success',1); await add('success',2); await add('success',3); r=await health();
check('recent recovery preserves seven-day partial count',()=>assert.deepEqual([r.state,r.partial_7d,r.failed_in_last_3],['degraded',1,0]));
let rows=await all();
check('critical rows sort ahead of partial-only degraded',()=>assert.equal(rows.at(-1).edge_name,edge));
await db.query("INSERT INTO cron_run_log VALUES('auto-transition-sits',now(),now(),'success',NULL)");
rows=await all();
check('partial-only degraded sorts ahead of healthy',()=>assert.ok(rows.findIndex(x=>x.edge_name===edge)<rows.findIndex(x=>x.edge_name==='auto-transition-sits')));
await db.exec("SET fixture.is_admin='false'");
await assert.rejects(all(),/Not authorized/); passed.push('non-admin guard preserved');
await db.exec("SET fixture.is_admin='true'");
await assert.rejects(db.exec(migration),/definition changed/); await db.exec('ROLLBACK'); passed.push('replay or drift rejected by definition guard');
await db.close();
console.log(JSON.stringify({passed:true,count:passed.length,tests:passed},null,2));
